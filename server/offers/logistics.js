/** Код региона по адресу/названию города, а если города нет в списке — по названию области, края, республики. */
function regionFromText(text) {
  const t = String(text || '').toLowerCase().replace(/ё/g, 'е');
  const m = RE_CITY.exec(t.replace(/орел/g, 'орёл'));
  if (m) {
    const key = m[1].toLowerCase().replace(/ /g, '-');
    const code = CITY_TO_REGION[key] ?? CITY_TO_REGION[m[1].toLowerCase()];
    if (code != null) return code;
  }
  return SUBJECTS.find(([re]) => re.test(t))?.[1] ?? null;
}

/** Код региона по ИНН (первые две цифры — код налогового органа, обычно совпадает с регионом). */
function regionFromInn(inn) {
  const code = Number(String(inn || '').slice(0, 2));
  return REGIONS[code] ? code : null;
}

function distanceKm(fromRegion, toRegion) {
  const a = REGIONS[fromRegion];
  const b = REGIONS[toRegion];
  if (!a || !b) return null;
  const rad = (x) => (x * Math.PI) / 180;
  const dLat = rad(b[1] - a[1]);
  const dLon = rad(b[2] - a[2]);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(rad(a[1])) * Math.cos(rad(b[1])) * Math.sin(dLon / 2) ** 2;
  return Math.round(2 * 6371 * Math.asin(Math.sqrt(h)));
}

const LOGISTICS_DEFAULTS = {
  road_coef: 1.3,            // дорога длиннее прямой примерно на треть
  km_per_day: 500,           // средняя скорость доставки ТК, км в сутки
  handling_days: 2,          // отгрузка у продавца и выдача у ТК
  min_cost: 1500,            // минимальная стоимость отправки, ₽
  contract_signing_days: 7,  // от итогов торгов до заключения контракта — не входит в срок поставки
  reserve_days: 1,           // запас на непредвиденное
};

/**
 * Перевозчики по тарифной сетке (config/logistics.json): стоимость и срок для партии — от дешёвого к дорогому.
 * Расчётный вес — больший из фактического и объёмного. Сетка ориентировочная: это оценка, а не тариф перевозчика.
 * @returns {Array<{id, name, cost, days, chargeable_kg}>}
 */
function quoteCarriers({ roadKm, weightKg, volumeM3, settings }) {
  if (roadKm == null || !(weightKg > 0)) return [];
  const chargeable = Math.max(weightKg, (volumeM3 || 0) * (settings?.volumetric_kg_per_m3 || 200));
  const out = [];
  for (const c of settings?.carriers || []) {
    if (c.max_kg && chargeable > c.max_kg) continue; // такой груз этот перевозчик не возит
    const zone = c.zones.find((z) => z.to_km == null || roadKm <= z.to_km) || c.zones[c.zones.length - 1];
    out.push({
      id: c.id, name: c.name,
      cost: Math.max(Number(c.min) || 0, Math.round(Number(zone.base || 0) + Number(zone.per_kg || 0) * chargeable)),
      // небольшое отправление идёт посылкой — у неё свои сроки (быстрее сборного груза)
      days: ((small) => (Number(small.handling_days) || 0) + Math.ceil(roadKm / (Number(small.km_per_day) || 500)))(c.parcel && chargeable <= Number(c.parcel.max_kg) ? c.parcel : c),
      chargeable_kg: Math.round(chargeable * 10) / 10,
    });
  }
  return out.sort((x, y) => x.cost - y.cost || x.days - y.days);
}

/**
 * Оценка доставки одного предложения.
 * @param {{sellerRegion, customerRegion, goodsCost, sellerDeliveryDays?, sellerDeliveryCost?, deliveryTermDays, logisticsPct, settings?,
 *   cargo?: {weight_kg, volume_m3, estimated}, quantity?: number, logistics?: object}} p
 *   cargo — вес и объём единицы товара (cargo.js), quantity — сколько единиц везём, logistics — тарифная сетка (loadLogistics)
 * @returns {{distance_km, delivery_days, delivery_cost, in_time, note, estimated, carrier, basis, options}}
 *   carrier — кто везёт: «продавец», название перевозчика или null (оценка без перевозчика); basis — на чём основана цифра
 */
function estimateDelivery(p) {
  const s = { ...LOGISTICS_DEFAULTS, ...(p.settings || {}) };
  const dist = p.sellerRegion && p.customerRegion ? distanceKm(p.sellerRegion, p.customerRegion) : null;
  const road = dist == null ? null : Math.round(dist * s.road_coef);

  let days;
  let dayNote;
  if (p.sellerDeliveryDays != null) { days = p.sellerDeliveryDays; dayNote = 'срок указал продавец'; }
  else if (road != null) { days = s.handling_days + Math.ceil(road / s.km_per_day); dayNote = `≈${road} км по дорогам`; }
  else { days = null; dayNote = 'регион продавца не известен'; }

  let cost;
  let costNote;
  let carrier = null;
  let basis;
  let options = [];
  if (p.sellerDeliveryCost != null) {
    // Продавец доставляет сам и назвал цену — это надёжнее любой оценки.
    cost = p.sellerDeliveryCost; costNote = 'стоимость указал продавец'; carrier = 'продавец'; basis = 'страница продавца';
  } else {
    const qty = p.quantity > 0 ? p.quantity : 1;
    if (p.cargo?.weight_kg > 0 && p.logistics) {
      options = quoteCarriers({ roadKm: road, weightKg: p.cargo.weight_kg * qty, volumeM3: (p.cargo.volume_m3 || 0) * qty, settings: p.logistics });
    }
    // Из перевозчиков — самый дешёвый из тех, кто успевает к сроку контракта; никто не успевает — просто самый дешёвый.
    const term = p.deliveryTermDays;
    const pick = options.find((o) => term == null || o.days + s.reserve_days <= term) || options[0] || null;
    if (pick) {
      cost = pick.cost; carrier = pick.name;
      basis = p.cargo.estimated ? 'оценка по тарифной сетке; вес и объём — оценка по виду товара' : 'оценка по тарифной сетке';
      costNote = `${pick.name}: ${basis}, расчётный вес ${pick.chargeable_kg} кг`;
      if (p.sellerDeliveryDays == null) { days = pick.days; dayNote = `≈${road} км по дорогам`; }
    } else {
      // Чем дальше, тем дороже: половина базовой доли логистики в своём регионе, до двойной на другой конец страны
      const factor = road == null ? 1 : road < 300 ? 0.5 : road < 1500 ? 1 : road < 4000 ? 1.5 : 2;
      cost = Math.max(s.min_cost, Math.round((p.goodsCost || 0) * ((p.logisticsPct ?? 5) / 100) * factor));
      costNote = 'оценка по расстоянию';
      basis = road == null ? 'оценка: регион продавца не известен' : 'оценка по расстоянию: вес товара не известен';
    }
  }

  const term = p.deliveryTermDays;
  const inTime = days == null || term == null ? null : days + s.reserve_days <= term;
  return {
    distance_km: road,
    delivery_days: days,
    delivery_cost: cost,
    in_time: inTime,
    estimated: p.sellerDeliveryCost == null,
    note: `${dayNote}; ${costNote}`,
    carrier,
    basis,
    options: options.slice(0, 3),
  };
}

