// «недостаточно данных» — разбор неполный или нет существенных сведений: это не оговорка, а отсутствие вывода.
const RECOMMENDATIONS = ['участвовать', 'участвовать с оговорками', 'не участвовать', 'недостаточно данных'];

const FIELD_KEYS = GROUPS.flatMap((g) => g.fields.map(([key]) => key));

/** Список полей для промпта; keys — только эти поля (прицельный дочит). */
function fieldsForPrompt(keys = null) {
  return GROUPS.map((g) => [g, g.fields.filter(([key]) => !keys || keys.includes(key))])
    .filter(([, fields]) => fields.length)
    .map(([g, fields]) => `${g.title}:\n` + fields.map(([key, label, hint]) => `- ${key} — ${label} (${hint})`).join('\n'))
    .join('\n\n');
}

