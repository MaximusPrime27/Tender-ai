// О чём сообщают уведомления. Общее условие — цены всех позиций подтверждены (товар найден в магазинах или цена
// введена вручную), закупка в работе и срок подачи не прошёл. Дальше — по расчёту прибыли:
//   profit — «выгодно»: прибыль не ниже порогов из профиля;
//   edge   — «на грани»: прибыль есть, но ниже порога — стоит посмотреть, можно ли дешевле привезти или купить;
//   found  — цена заказчика не указана (запрос цен на площадке): прибыль посчитать нельзя, но товар найден —
//            известна себестоимость, можно предложить свою цену.

// agent — выгодную закупку нашёл агент заявок (при ожидаемом снижении, с заменой товара и т. п.): в силе, пока закупка в работе
const KIND_RANK = { agent: 0, found: 1, edge: 2, profit: 3 };

/** @param t строка закупки с полями расчёта (status, deadline_at, price, econ_verdict, econ_confirmed) */
function alertKind(t, nowIso) {
  if (!t || t.status !== 'scored' || !t.econ_confirmed) return null;
  if (t.deadline_at && nowIso && t.deadline_at <= nowIso) return null;
  // Заказчик не назвал цену: даже если расчёт сделан от нашей собственной цены предложения, это по-прежнему
  // «товар найден» — выгодность тут зависит от того, какую цену мы сами поставили.
  if (!t.price) return ['выгодно', 'на грани', 'нет данных'].includes(t.econ_verdict) ? 'found' : null;
  if (t.econ_verdict === 'выгодно') return 'profit';
  if (t.econ_verdict === 'на грани') return 'edge';
  return null;
}

module.exports = { alertKind, KIND_RANK };
